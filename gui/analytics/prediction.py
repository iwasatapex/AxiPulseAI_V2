def render_analytics(st, result: Dict[str, Any], state: Dict[str, Any]) -> None:
    st.markdown("## Analytics")
    st.caption("Interpretation of this prediction derived from engine output "
               "and canonical KPI targets. Not a model calculation.")

    with st.expander("Key Metrics", expanded=True):
        oh = a.fnum(result.get("operational_health"))
        nps = a.fnum(result.get("nps"))
        m1, m2 = st.columns(2)
        m1.metric("Predicted OH", f"{oh:.1f}%" if oh is not None else "—")
        m2.metric("Predicted NPS", f"{nps:.1f}" if nps is not None else "—")

    with st.expander("Input State Summary", expanded=False):
        rows = input_summary(state)
        if rows:
            df = []
            for r in rows:
                met = {True: "Met", False: "Not met", None: "—"}[r["met"]]
                df.append({
                    "KPI": r["kpi"], "Value": a.disp(r["value"], 2), "Unit": r["unit"],
                    "Range": f"[{r['lo']:g}, {r['hi']:g}]",
                    "Target": a.disp(r["target"], 2),
                    "Met": met,
                })
            st.dataframe(df, width="stretch", hide_index=True)
        else:
            st.info(a.NA)

    with st.expander("KPI Target Comparison", expanded=False):
        rows = a.kpi_comparison_rows(state)
        if rows:
            df = []
            for r in rows:
                df.append({
                    "KPI": r["kpi"], "Value": a.disp(r["value"], 2),
                    "Target": a.disp(r["target"], 2),
                    "Gap": a.disp(r["gap"], 2),
                    "% target": a.disp(r["pct_of_target"], 1),
                    "Met": "Yes" if r["met"] is True else ("No" if r["met"] is False else "—"),
                })
            st.dataframe(df, width="stretch", hide_index=True)
            st.caption("Transfer: lower is better (met when ≤ target).")

    with st.expander("Confidence / Uncertainty", expanded=False):
        conf = confidence_info(result)
        if not conf["available"]:
            st.info("Point prediction — calibrated confidence unavailable.")
        else:
            c1, c2 = st.columns(2)
            c1.metric("OH confidence", f"{conf['oh_confidence']:.2f}" if conf["oh_confidence"] is not None else "—")
            iv = conf["oh_interval"]
            c1.write(f"OH interval: {iv if iv else '—'}")
            c2.metric("NPS confidence", f"{conf['nps_confidence']:.2f}" if conf["nps_confidence"] is not None else "—")
            iv = conf["nps_interval"]
            c2.write(f"NPS interval: {iv if iv else '—'}")
            st.caption("Confidence/interval values are the engine's calibrated output when present.")

    with st.expander("NPS Analytics", expanded=False):
        nps_a = nps_analytics(result)
        st.write("Causal order: ", nps_a["causal_order"])
        if nps_a["distribution"]:
            from gui import charts
            fig = charts.nps_distribution_chart(result.get("bayesian_score_distribution") or {})
            if fig:
                st.plotly_chart(fig, width="stretch", key="analytics_prediction_nps_distribution")
            st.caption("NPS 0..10 posterior distribution (engine ML-predicted output).")
        else:
            st.info("No NPS score distribution exposed by the engine.")
        if nps_a["survey_probabilities"]:
            st.json(nps_a["survey_probabilities"])

    with st.expander("Diagnostics", expanded=False):
        warns = prediction_diagnostics(result, state)
        if warns:
            for w in warns:
                st.warning(w)
        else:
            st.success("No diagnostic warnings flagged.")

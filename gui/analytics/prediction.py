"""Prediction analytics: interpretation of a single V2 prediction.

Pure analysis functions consume the ``predict`` result payload and the
input state dict. No prediction math is re-run here.
"""
from __future__ import annotations

from typing import Any, Dict, List, Optional

from gui.analytics import common as a
from gui import contracts as ct


def _input_label(key: str) -> str:
    """Canonical KPI label (NPS renamed to reflect observed prior-period)."""
    if key == "nps":
        return ct.NPS_INPUT_LABEL
    if key in ct.KPI:
        return ct.KPI[key]["label"]
    return key


def input_summary(state: Dict[str, Any]) -> List[Dict[str, Any]]:
    """Summarise the entered inputs against canonical ranges/targets."""
    rows = []
    order = [
        "total_calls_received", "quality", "competency", "attendance",
        "release", "transfer", "operations_health", "nps",
    ]
    for key in order:
        if key not in state:
            continue
        cfg = ct.KPI[key]
        val = a.fnum(state.get(key))
        rows.append({
            "kpi": _input_label(key),
            "value": val,
            "unit": cfg.get("unit", ""),
            "lo": cfg["min"],
            "hi": cfg["max"],
            "target": ct.kpi_target(key),
            "met": ct.kpi_met(key, val),
            "boundary": val is not None and (val == cfg["min"] or val == cfg["max"]),
        })
    return rows


def confidence_info(result: Dict[str, Any]) -> Dict[str, Any]:
    """Extract actual model uncertainty if the engine exposed it."""
    oh_conf = a.fnum(result.get("oh_confidence"))
    nps_conf = a.fnum(result.get("nps_confidence"))
    oh_lo, oh_hi = a.fnum(result.get("oh_lower")), a.fnum(result.get("oh_upper"))
    nps_lo, nps_hi = a.fnum(result.get("nps_lower")), a.fnum(result.get("nps_upper"))
    has_oh = any(v is not None for v in (oh_conf, oh_lo, oh_hi))
    has_nps = any(v is not None for v in (nps_conf, nps_lo, nps_hi))
    return {
        "oh_confidence": oh_conf,
        "oh_interval": (oh_lo, oh_hi) if oh_lo is not None and oh_hi is not None else None,
        "nps_confidence": nps_conf,
        "nps_interval": (nps_lo, nps_hi) if nps_lo is not None and nps_hi is not None else None,
        "available": has_oh or has_nps,
    }


def nps_analytics(result: Dict[str, Any]) -> Dict[str, Any]:
    """NPS output + normalized distribution + survey probabilities if present."""
    dist = result.get("bayesian_score_distribution") or {}
    norm = None
    try:
        norm = ct.normalize_nps_distribution(dist) if dist else None
    except ValueError:
        norm = None
    probs = {
        "promoters": a.fnum(result.get("promoters")),
        "passives": a.fnum(result.get("passives")),
        "detractors": a.fnum(result.get("detractors")),
    }
    return {
        "nps": a.fnum(result.get("nps")),
        "distribution": norm,
        "survey_probabilities": probs if any(v is not None for v in probs.values()) else None,
        # Accurate language: NPS is an engine-provided output derived from the
        # predicted survey-score distribution (promoters 9-10 − detractors 0-6),
        # not a rule-based survey simulation and not a direct function of OH.
        "causal_order": "NPS is ML-predicted by the engine from the score "
                        "distribution (promoters 9-10 − detractors 0-6); "
                        "it is not generated by a rule-based survey chain.",
    }


def prediction_diagnostics(result: Dict[str, Any], state: Dict[str, Any]) -> List[str]:
    """Derived diagnostic warnings from the prediction + inputs."""
    warnings: List[str] = []
    for row in input_summary(state):
        if row["met"] is False:
            warnings.append(f"{row['kpi']} below target ({row['value']} vs {row['target']}).")
        if row["boundary"]:
            warnings.append(f"{row['kpi']} is at the canonical boundary.")
    errs = result.get("errors")
    if errs:
        warnings.append("Model reported errors: " + "; ".join(str(e) for e in errs))
    if result.get("operational_health") is None or result.get("nps") is None:
        warnings.append("Prediction returned no OH/NPS output.")
    return warnings


